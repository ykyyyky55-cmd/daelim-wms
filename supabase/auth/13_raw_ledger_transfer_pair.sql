-- ==============================================================================
-- 원료수불부 거점이동 짝 전표 (wms_raw_ledger.pair_id)
-- ==============================================================================
-- 거점이동은 같은 날짜에 두 전표로 기록한다: 보낸 지역 '이동출고'(불) + 받은 지역 '이동입고'(수).
-- 두 전표는 같은 pair_id를 가지며, 앱은 한쪽을 수정·삭제하면 다른 쪽도 함께 바꾼다.
-- 예전 방식의 한 줄짜리 '이동' 전표는 pair_id가 비어 있다 (앱의 수정 창에서 받는 곳을 지정하면 짝이 생긴다).
-- 여러 번 실행해도 안전하다.
-- ==============================================================================

ALTER TABLE public.wms_raw_ledger ADD COLUMN IF NOT EXISTS pair_id TEXT;
CREATE INDEX IF NOT EXISTS idx_wms_raw_ledger_pair ON public.wms_raw_ledger (pair_id) WHERE pair_id IS NOT NULL;
