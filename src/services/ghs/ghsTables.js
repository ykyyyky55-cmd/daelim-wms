const CLASS_BY_KEY = new Map(GHS_CLASSES.map(c => [c.key, c]));
export const classOf = (key) => CLASS_BY_KEY.get(key) || null;
export const catOf = (key, k) => classOf(key)?.cats.find(x => x.k === String(k)) || null;
export const INH_FORMS = { GAS: '가스', VAPOR: '증기', DUST: '분진/미스트' };

/**
 * 분류 한 줄의 표시 글자 (예: '인화성 액체 : 구분 2', '급성 독성(흡입: 증기) : 구분 3')
 * @param {{ c: string, k: string, form?: string }} entry
 */
export const clsLabel = (entry) => {
    const cls = classOf(entry.c), ct = catOf(entry.c, entry.k);
    if (!cls) return `${entry.c} : ${entry.k}`;
    const name = entry.c === 'ACUTE_INH' ? `급성 독성(흡입${entry.form && INH_FORMS[entry.form] ? `: ${INH_FORMS[entry.form]}` : ''})` : cls.label;
    return `${name} : ${ct ? ct.label : entry.k}`;
};

