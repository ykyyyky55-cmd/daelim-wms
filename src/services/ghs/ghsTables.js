/** 그 분류의 한계농도 (%) */
export const cutoffOf = (entry) => {
    const cls = classOf(entry.c);
    if (!cls) return 1;
    if (cls.group === 'PHYS') return PHYS_CUTOFF;
    const v = CUTOFF[entry.c];
    return typeof v === 'object' ? (v[entry.k] ?? 1) : (v ?? 1);
};

