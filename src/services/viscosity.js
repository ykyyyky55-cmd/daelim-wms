// ---------- 온도별 동점도 (ASTM D341) ----------
const zOf = (v) => v + 0.7 + Math.exp(-1.47 - 1.84 * v - 0.51 * v * v);
const vOf = (z) => { const x = z - 0.7; return x - Math.exp(-0.7487 - 3.295 * x + 0.6119 * x * x - 0.3193 * x * x * x); };
/**
 * 두 온도의 동점도로 Walther 식 계수를 구해 다른 온도의 동점도를 돌려주는 함수를 만든다
 * @returns {((t: number) => number) | null}
 */
export const waltherFit = (t1, v1, t2, v2) => {
    if (!(v1 > 0 && v2 > 0) || t1 === t2) return null;
    const T1 = Math.log10(t1 + 273.15), T2 = Math.log10(t2 + 273.15);
    const L1 = Math.log10(Math.log10(zOf(v1))), L2 = Math.log10(Math.log10(zOf(v2)));
    const B = (L1 - L2) / (T2 - T1);
    const A = L1 + B * T1;
    return (t) => vOf(10 ** (10 ** (A - B * Math.log10(t + 273.15))));
};

// ---------- 15℃ 밀도·비중 (ASTM D1250 / API MPMS 11.1, 1980 표) ----------
// α15 = K0/ρ15² + K1/ρ15 (전이 구간은 A + B/ρ15²), VCF = exp(-α15·Δt·(1 + 0.8·α15·Δt)), ρt = ρ15 × VCF
export const D1250_GROUPS = {
    LUBE: { label: '윤활유 (표 54D)', range: '800~1,164 kg/㎥' },
    AUTO: { label: '석유제품 자동 (표 54B, 밀도로 유종 선택)', range: '653~1,075 kg/㎥' },
    FUEL: { label: '연료유·경유 (표 54B)', range: '839~1,075 kg/㎥' },
    JET: { label: '등유·제트유 (표 54B)', range: '788~839 kg/㎥' },
    GASOLINE: { label: '휘발유 (표 54B)', range: '653~770 kg/㎥' },
    CRUDE: { label: '원유 (표 54A)', range: '610~1,075 kg/㎥' }
};
const alphaOf = (group, rho) => {
    const k = (k0, k1) => k0 / (rho * rho) + k1 / rho;
    switch (group) {
        case 'LUBE': return k(0, 0.6278);
        case 'CRUDE': return k(613.9723, 0);
        case 'FUEL': return k(186.9696, 0.4862);
        case 'JET': return k(594.5418, 0);
        case 'GASOLINE': return k(346.4228, 0.4388);
        default: // 표 54B 자동
            if (rho >= 838.5) return k(186.9696, 0.4862);
            if (rho >= 787.5) return k(594.5418, 0);
            if (rho >= 770.5) return -0.00336312 + 2680.3206 / (rho * rho);
            return k(346.4228, 0.4388);
    }
};
export const vcfOf = (group, rho15, t) => { const a = alphaOf(group, rho15); const dt = t - 15; return Math.exp(-a * dt * (1 + 0.8 * a * dt)); };
/**
 * 측정 온도의 밀도(또는 t/4℃ 비중)로 15℃ 밀도
 * @param {number} obs 측정값 (2 미만이면 g/㎤·비중, 그 이상이면 kg/㎥)
 * @returns {{ rho15: number, sg154: number, sg1515: number, vcf: number } | null}
 */
export const density15 = (obs, t, group = 'LUBE') => {
    if (!(obs > 0) || !Number.isFinite(t)) return null;
    const rhoT = obs < 2 ? obs * 1000 : obs;
    let rho15 = rhoT;
    for (let i = 0; i < 50; i++) { const next = rhoT / vcfOf(group, rho15, t); if (Math.abs(next - rho15) < 1e-6) { rho15 = next; break; } rho15 = next; }
    return { rho15, sg154: rho15 / 999.972, sg1515: rho15 / 999.1, vcf: vcfOf(group, rho15, t) };
};
/** 원본 앱의 간이 계수법: SG15 = SGt + k × (t − 15) */
export const SIMPLE_COEF = { 휘발유: 0.00090, 등유: 0.00075, 경유: 0.00070, 윤활유: 0.00065, 중유: 0.00062 };
export const sg15Simple = (sg, t, kind = '윤활유') => sg + (SIMPLE_COEF[kind] || 0) * (t - 15);
