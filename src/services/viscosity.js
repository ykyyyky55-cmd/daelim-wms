// L·H는 KV100에 대해 거의 거듭제곱 꼴이라 log-log 공간에서 가까운 3점 2차 보간을 쓴다 (표의 빈 구간에서도 매끄럽게)
const lagrange = (pts, x) => pts.reduce((s, [xi, yi], i) => s + yi * pts.reduce((p, [xj], j) => (i === j ? p : p * (x - xj) / (xi - xj)), 1), 0);
export const lhOf = (y) => {
    if (y > 70) return { l: 0.8353 * y * y + 14.67 * y - 216.0, h: 0.1684 * y * y + 11.85 * y - 97.0, fromTable: false };
    const exact = ASTM.find(r => Math.abs(r[0] - y) < 1e-9);
    if (exact) return { l: exact[1], h: exact[2], fromTable: true };
    const near = [...ASTM].sort((a, b) => Math.abs(a[0] - y) - Math.abs(b[0] - y)).slice(0, 3).sort((a, b) => a[0] - b[0]);
    const lx = Math.log(y);
    const l = Math.exp(lagrange(near.map(r => [Math.log(r[0]), Math.log(r[1])]), lx));
    const h = Math.exp(lagrange(near.map(r => [Math.log(r[0]), Math.log(r[2])]), lx));
    return { l, h, fromTable: false };
};
/** 점도지수. u = KV40, y = KV100 (cSt). KV100 < 2이면 null */
export const viscosityIndex = (u, y) => {
    if (!(u > 0) || !(y >= 2)) return null;
    const { l, h } = lhOf(y);
    if (u >= h) return { vi: ((l - u) / (l - h)) * 100, l, h, proc: 'A' };
    const n = (Math.log10(h) - Math.log10(u)) / Math.log10(y);
    return { vi: (10 ** n - 1) / 0.00715 + 100, l, h, proc: 'B' };
};
/** KV40과 목표 VI로 KV100 (이분법) */
export const kv100For = (u, vi) => {
    if (!(u > 0) || !Number.isFinite(vi)) return null;
    let lo = 2, hi = Math.max(u, 3) + 500;
    const f = (y) => viscosityIndex(u, y)?.vi ?? NaN;
    if (!(f(lo) <= vi) || !(f(hi) >= vi)) return null; // 범위 밖
    for (let i = 0; i < 200 && hi - lo > 1e-7; i++) { const m = (lo + hi) / 2; if (f(m) < vi) lo = m; else hi = m; }
    return (lo + hi) / 2;
};
/** KV100과 목표 VI로 KV40 */
export const kv40For = (y, vi) => {
    if (!(y >= 2) || !Number.isFinite(vi)) return null;
    const { l, h } = lhOf(y);
    if (vi <= 100) return l - (vi / 100) * (l - h);
    const n = Math.log10((vi - 100) * 0.00715 + 1);
    return 10 ** (Math.log10(h) - n * Math.log10(y));
};
