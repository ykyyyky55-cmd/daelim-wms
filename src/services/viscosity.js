// ---------- 혼합 점도 ----------
/** ÖleZol 혼합지수 (원본 앱 방식): VBI = log v / (3.947 + log v) */
const oleVbi = (v) => (v > 0 ? Math.log10(v) / (3.947 + Math.log10(v)) : 0);
const oleInv = (b) => (b > 0 && b < 1 ? 10 ** ((3.947 * b) / (1 - b)) : 0);
/** Refutas 혼합지수: VBN = 14.534 × ln(ln(v + 0.8)) + 10.975 (v: cSt, 중량비로 가중) */
const refVbn = (v) => (v > 0.2 ? 14.534 * Math.log(Math.log(v + 0.8)) + 10.975 : 0);
const refInv = (n) => Math.exp(Math.exp((n - 10.975) / 14.534)) - 0.8;

export const BLEND_METHODS = {
    OLEZOL: { label: 'ÖleZol 혼합지수 (기존 앱 방식)', idx: oleVbi, inv: oleInv },
    REFUTAS: { label: 'Refutas 혼합지수 (ASTM D7152 계열, 중량비)', idx: refVbn, inv: refInv }
};
/**
 * 여러 성분 혼합 점도
 * @param {{ v: number, w: number }[]} parts 동점도(cSt)·비율(%)
 */
export const blendViscosity = (parts, method = 'OLEZOL') => {
    const M = BLEND_METHODS[method] || BLEND_METHODS.OLEZOL;
    const ok = parts.filter(p => p.v > 0 && p.w > 0);
    const total = ok.reduce((s, p) => s + p.w, 0);
    if (!total) return { v: 0, index: 0, total: 0 };
    const index = ok.reduce((s, p) => s + (p.w / total) * M.idx(p.v), 0); // 비율 합이 100이 아니어도 정규화
    return { v: M.inv(index), index, total };
};
/** 두 성분으로 목표 점도를 만드는 #1 비율(%) — 목표가 두 점도 사이가 아니면 null */
export const blendRatioFor = (v1, v2, target, method = 'OLEZOL') => {
    const M = BLEND_METHODS[method] || BLEND_METHODS.OLEZOL;
    if (!(v1 > 0 && v2 > 0 && target > 0) || v1 === v2) return null;
    if (target <= Math.min(v1, v2) || target >= Math.max(v1, v2)) return null;
    return ((M.idx(target) - M.idx(v2)) / (M.idx(v1) - M.idx(v2))) * 100;
};

