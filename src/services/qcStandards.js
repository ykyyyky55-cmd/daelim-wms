/** 제품명으로 서식을 짐작 (예: '5W-30' → 엔진오일, 'DOT4' → 브레이크액) */
export const guessProductTemplate = (name) => {
    const n = String(name || '').toUpperCase();
    if (/DOT\s?\d|브레이크|BF\d?/.test(n)) return '브레이크액';
    if (/\d{1,2}W-?\d{2}|엔진오일|디젤|가솔린|4T/.test(n)) return '엔진오일';
    if (/기어|GEAR|\d{2}W-?\d{2,3}|GL-?\d/.test(n)) return '기어유';
    if (/유압|HYD|ISO\s?VG|AW\s?\d{2}/.test(n)) return '유압유';
    if (/코팅|첨가|세척|제거|크린/.test(n)) return '첨가제·코팅제';
    return '기타';
};

