/** 사업장 */
export const QC_SITES = { HQ: '본사', GIMPO: '김포' };

/**
 * 위치·작업장 글자에서 사업장을 고른다 (예: '김포공장 / 2동' → GIMPO, '본사 / 제품창고' → HQ)
 * @param {string} text
 * @returns {'HQ' | 'GIMPO' | ''}
 */
export const siteFromText = (text) => {
    const t = String(text || '');
    if (/김포/.test(t)) return 'GIMPO';
    if (/본사|방산/.test(t)) return 'HQ';
    return '';
};

/** 기록의 사업장 (예전 기록은 공정·비고 글자로 짐작) */
export const siteOf = (rec) => (QC_SITES[rec?.site] ? rec.site : siteFromText(`${rec?.process || ''} ${rec?.notes || ''} ${rec?.place || ''}`));

